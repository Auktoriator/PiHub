class Words:
    def __init__(self, lang: str):
        self.lang = lang if lang in TEXTS else "en"

    def __call__(self, key: str, **params) -> str:
        template = TEXTS[self.lang].get(key) or TEXTS["en"][key]
        return template.format(**params)


